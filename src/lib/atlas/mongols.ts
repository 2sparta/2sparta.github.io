export function campaignThrough(year: number, step?: string) {
  const i = MONGOL_CAMPAIGN.findIndex((x) => x.id === step);
  return MONGOL_CAMPAIGN.filter(
    (x, n) => x.year <= year && (i < 0 || MONGOL_CAMPAIGN[i].year !== year || n <= i),
  );
}
export function campaignPlaces(year: number, step?: string): AtlasPlace[] {
  return year >= 1223 && year <= 1242
    ? campaignThrough(year, step).map((x) => ({
        id: `campaign-${x.id}`,
        name: x.name,
        type: "city",
        from: x.year,
        to: 1242,
        lat: x.lat,
        lng: x.lng,
        dateLabel: x.label,
        description: x.description,
        sources: ["mongol-invasion"],
        mongol: true,
        campaign: x.outcome,
      }))
    : [];
}
export function markInvadedRus(
  collection: HistoricalCollection | undefined,
  year: number,
  step?: string,
) {
  if (!collection) return collection;
  const names = new Set(
    campaignThrough(year, step)
      .map((x) => x.polity)
      .filter(Boolean),
  );
  return {
    ...collection,
    features: collection.features.map((f) =>
      names.has(f.properties.name) ? { ...f, properties: { ...f.properties, invaded: true } } : f,
    ),
  };
}

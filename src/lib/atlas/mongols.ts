export type MongolFrame = {
  year: number;
  to: number;
  branch: "mongols" | "hordes" | "mughals";
  sourceYear: number;
  sourceFilename: string;
  sourceUrl: string;
  originalPath: string;
  author: string;
  license: string;
  sourceId: string;
  note: string;
  collection: HistoricalCollection;
};
export type MongolData = { frames: MongolFrame[] };
export const MONGOL_YEARS = [
  1206, 1219, 1223, 1227, 1237, 1259, 1294, 1300, 1500, 1530, 1600, 1605, 1700, 1707,
] as const;
export function validateMongolData(raw: unknown): MongolData {
  const d = raw as MongolData;
  if (!d || !Array.isArray(d.frames) || d.frames.length !== MONGOL_YEARS.length)
    throw new Error("INVALID_MONGOL_DATA");
  d.frames.forEach((f, i) => {
    if (f.year !== MONGOL_YEARS[i] || f.to < f.year || f.sourceYear > f.year || !f.note)
      throw new Error("INVALID_MONGOL_DATA");
    validateHistoricalCollection(f.collection);
    if (
      f.collection.features.some(
        (x) => x.properties.region !== "mongols" || (x.properties.validTo ?? 0) < f.year,
      )
    )
      throw new Error("INVALID_MONGOL_DATA");
  });
  return d;
}
export function mongolFrameAt(data: MongolData | undefined, year: number, branch?: string) {
  return data?.frames
    .filter(
      (f) =>
        year >= f.year &&
        year <= f.to &&
        (!branch ||
          branch === "mongols" ||
          f.branch === branch ||
          (branch === "hordes" && f.year === 1300)),
    )
    .at(-1);
}
export function mongolCollectionAt(
  data: MongolData | undefined,
  year: number,
): HistoricalCollection | undefined {
  if (year < 1206 || year > 1858) return undefined;
  const frames = data?.frames.filter((f) => year >= f.year && year <= f.to);
  if (!frames) return undefined;
  return {
    type: "FeatureCollection",
    features: frames
      .flatMap((f) => f.collection.features.filter((x) => year <= (x.properties.validTo ?? f.to)))
      .map((x) =>
        year >= 1260 && x.properties.name === "Mongol Empire"
          ? {
              ...x,
              properties: {
                ...x.properties,
                name: "Монгольські улуси — сукупний контур 1259",
                subject: "Mongol successor realms",
              },
            }
          : x,
      ),
  };
}

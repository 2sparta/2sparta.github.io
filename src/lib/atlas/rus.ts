import type { AtlasEvent, AtlasPlace, AtlasSource, HistoricalCollection } from "./model";
import { RUS_YEARS, validateHistoricalCollection } from "./model.ts";

export type RusFrame = {
  year: number;
  sourceYear: number;
  sourceFilename: string;
  sourceUrl: string;
  originalPath: string;
  author: string;
  license: string;
  sourceId: string;
  note: string;
  collection: HistoricalCollection;
};
export type RusData = { frames: RusFrame[] };
export function validateRusData(raw: unknown): RusData {
  const data = raw as RusData;
  if (!data || !Array.isArray(data.frames) || data.frames.length !== RUS_YEARS.length)
    throw new Error("INVALID_RUS_DATA");
  data.frames.forEach((frame, i) => {
    if (
      frame.year !== RUS_YEARS[i] ||
      frame.sourceYear > frame.year ||
      !frame.note ||
      !frame.originalPath.startsWith("atlas/rus/originals/")
    )
      throw new Error("INVALID_RUS_DATA");
    validateHistoricalCollection(frame.collection);
    if (
      frame.collection.features.some(
        (f) =>
          f.properties.region !== "rus" ||
          !f.properties.detailed ||
          f.properties.sourceYear !== frame.sourceYear,
      )
    )
      throw new Error("INVALID_RUS_DATA");
  });
  return data;
}

